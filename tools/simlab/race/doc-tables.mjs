#!/usr/bin/env node
/* doc-tables.mjs — the measured tables quoted in
 * docs/proposals/2026-10-race-to-the-top.md, generated from the committed
 * race-lab artifact so no number in the doc is retyped by hand.
 *
 *   node tools/simlab/race/doc-tables.mjs [--condensed] [--in artifacts/t104-race/baseline.json]
 *
 * --condensed prints exactly the Tables M1–M8 embedded in the proposal's §2;
 * without it, every table for every viewport.
 *
 * Prints markdown. Cells are `median [min–max]` over a group's runs unless the
 * header says otherwise. Read the honesty notes in tools/simlab/README.md
 * ("race lab") before quoting a bot row: bots are reflex players, the oracle
 * rows are the authored floor of the course.                               */

import { readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(here, '..', '..', '..');
const argv = process.argv.slice(2);
const opt = (n, d) => { const i = argv.indexOf('--' + n); return i >= 0 ? argv[i + 1] : d; };
const doc = JSON.parse(readFileSync(resolve(ROOT, opt('in', 'artifacts/t104-race/baseline.json')), 'utf8'));
const A = doc.aggregate;
const row = (group, vp) => A.find((r) => r.group === group && r.viewport === vp);
const m = (d, digits = 1) => d && d.n ? fmtN(d.median, digits) : '—';
const mr = (d, digits = 1) => d && d.n ? `${fmtN(d.median, digits)} [${fmtN(d.min, digits)}–${fmtN(d.max, digits)}]` : '—';
const pct = (d) => d && d.n ? `${Math.round(d.median * 100)}% [${Math.round(d.min * 100)}–${Math.round(d.max * 100)}]` : '—';
function fmtN(v, digits) { return v === null || v === undefined ? '—' : Number(v).toFixed(digits); }

const GROUPS = ['oracle@0', 'oracle@1500', 'oracle@3000', 'rush', 'climber', 'fighter', 'carried', 'idle'];
const CONDENSED = argv.includes('--condensed');
const VPS = ['desktop-16x10', 'phone-landscape', 'phone-landscape-6pct', 'phone-portrait'];
const out = [];
const P = (s = '') => out.push(s);

P('<!-- generated by node tools/simlab/race/doc-tables.mjs' + (CONDENSED ? ' --condensed' : '') + ' from ' + opt('in', 'artifacts/t104-race/baseline.json') + ', digest ' + doc.digest + ' -->');
P();
if (CONDENSED) { condensed(); console.log(out.join('\n')); process.exit(0); }
P('### Table M1 — run outcomes (all viewports)');
P();
P('| group | viewport | n | outcomes | sides cleared | run seconds | victory seconds | lives lost | lethal events |');
P('|---|---|---:|---|---|---|---|---|---|');
for (const vp of VPS) for (const g of GROUPS) {
  const r = row(g, vp); if (!r) continue;
  P(`| ${g} | ${vp} | ${r.n} | ${Object.entries(r.outcomes).map(([k, v]) => `${k} ${v}`).join(', ')} | ${mr(r.facesCleared, 0)} | ${mr(r.runSeconds)} | ${mr(r.victorySeconds)} | ${mr(r.livesLost, 0)} | ${mr(r.lethalEvents, 0)} |`);
}
P();

for (const vp of VPS) {
  P(`### Table M2-${vp} — seconds per side (moving / waiting at the closed joint / gate held), median [min–max] over sides cleared`);
  P();
  P('| group | side 1 | side 2 | side 3 | side 4 | side 5 | side 6 |');
  P('|---|---|---|---|---|---|---|');
  for (const g of GROUPS) {
    const r = row(g, vp); if (!r) continue;
    P(`| ${g} total | ${r.perFace.map((f) => f.cleared ? `${mr(f.faceSeconds)} (n=${f.cleared})` : `— (0 of ${f.reached})`).join(' | ')} |`);
    P(`| ${g} moving | ${r.perFace.map((f) => mr(f.movingSeconds)).join(' | ')} |`);
    P(`| ${g} wait at joint | ${r.perFace.map((f) => mr(f.pivotWaitSeconds)).join(' | ')} |`);
    P(`| ${g} gate held | ${r.perFace.map((f) => mr(f.gateHeldSeconds)).join(' | ')} |`);
  }
  P();
}

P('### Table M3 — gate held (seconds the scroll is frozen in `gate` state), every side REACHED, including sides never cleared');
P();
P('| group | viewport | gate 1 | gate 2 | gate 3 | gate 4 | gate 5 | gate 6 | drive-through rate by gate |');
P('|---|---|---|---|---|---|---|---|---|');
for (const vp of VPS) for (const g of GROUPS) {
  const r = row(g, vp); if (!r) continue;
  P(`| ${g} | ${vp} | ${r.perFace.map((f) => mr(f.gateStateSecondsAll)).join(' | ')} | ${r.perFace.map((f) => f.driveThroughRate ?? '—').join(' / ')} |`);
}
P();

P('### Table M4 — vertical metres (desktop-16x10)');
P();
P('`peak above deck` = highest local y above that side\'s lowest deck column (tiles = metres on the HUD). `net ALT` = HUD ALT at the next side\'s entry minus this side\'s entry (helix + local y). `climb-up` = sum of every upward Δy (all climbing done, including climbs later given back).');
P();
P('| group | metric | side 1 | side 2 | side 3 | side 4 | side 5 | side 6 |');
P('|---|---|---|---|---|---|---|---|');
for (const g of GROUPS) {
  const r = row(g, 'desktop-16x10'); if (!r) continue;
  P(`| ${g} | peak above deck | ${r.perFace.map((f) => mr(f.peakAboveDeck)).join(' | ')} |`);
  P(`| ${g} | net ALT gain m | ${r.perFace.map((f) => mr(f.netAltGain)).join(' | ')} |`);
  P(`| ${g} | net ALT m/s | ${r.perFace.map((f) => mr(f.netAltPerSecond, 2)).join(' | ')} |`);
  P(`| ${g} | climb-up m/s | ${r.perFace.map((f) => mr(f.climbUpPerSecond, 2)).join(' | ')} |`);
  P(`| ${g} | share of time ≥ 6 above deck | ${r.perFace.map((f) => pct(f.shareAbove6)).join(' | ')} |`);
}
P();

P('### Table M5 — moving forward vs waiting (whole run, share of frames)');
P();
P('`forward` = RIG advanced ≥ 1 tile/s that frame. `scroll held` = the pursuing edge did not move (gate, joint approach, ritual, end clamp). `pinned` = RIG pressed against the right clamp (screen edge or closed joint). `idle` = the harness A.5 definition (grounded, |vx| < 2, free).');
P();
P('| group | viewport | forward | scroll held | pinned at right clamp | idle |');
P('|---|---|---|---|---|---|');
for (const vp of VPS) for (const g of GROUPS) {
  const r = row(g, vp); if (!r) continue;
  P(`| ${g} | ${vp} | ${pct(r.shareForward)} | ${pct(r.shareScrollHeld)} | ${pct(r.sharePinnedRight)} | ${pct(r.shareIdle)} |`);
}
P();

P('### Table M6 — deaths per side (desktop-16x10): lethal events (HULL FALLBACK absorbed + lives spent) / lives spent');
P();
P('| group | side 1 | side 2 | side 3 | side 4 | side 5 | side 6 |');
P('|---|---|---|---|---|---|---|');
for (const g of GROUPS) {
  const r = row(g, 'desktop-16x10'); if (!r) continue;
  P(`| ${g} | ${r.perFace.map((f) => f.reached ? `${mr(f.lethalEvents, 0)} / ${mr(f.livesLost, 0)}` : '—').join(' | ')} |`);
}
P();

P('### Table M7 — how far ahead RIG can see (tiles between RIG\'s front and the right screen edge, all PLAYING frames)');
P();
P('| group | viewport | p10 | p25 | median | p75 | p90 | share of frames < 3 tiles | < 8 tiles |');
P('|---|---|---:|---:|---:|---:|---:|---:|---:|');
for (const vp of VPS) for (const g of GROUPS) {
  const r = row(g, vp); if (!r || !r.lookaheadTiles) continue;
  const q = r.lookaheadTiles;
  P(`| ${g} | ${vp} | ${q.p10} | ${q.p25} | ${q.median} | ${q.p75} | ${q.p90} | ${Math.round(q.shareUnder3 * 100)}% | ${Math.round(q.shareUnder8 * 100)}% |`);
}
P();
const quantTable = (title, key) => {
  P(title);
  P();
  P('| group | viewport | p10 | p25 | median | p75 | p90 | share of frames < 3 tiles | < 8 tiles |');
  P('|---|---|---:|---:|---:|---:|---:|---:|---:|');
  for (const vp of VPS) for (const g of GROUPS) {
    const r = row(g, vp); const q = r && r[key]; if (!q) continue;
    P(`| ${g} | ${vp} | ${q.p10} | ${q.p25} | ${q.median} | ${q.p75} | ${q.p90} | ${Math.round(q.shareUnder3 * 100)}% | ${Math.round(q.shareUnder8 * 100)}% |`);
  }
  P();
};
quantTable('### Table M7 (route) — tiles of ROUTE ahead of RIG\'s front (right edge clipped at the next bend), frames where the scroll moves', 'routeAheadMovingTiles');
quantTable('### Table M7b — daylight behind RIG (RIG\'s back to the damage plane), all PLAYING frames', 'marginTiles');
if (doc.reachByPlay) {
  P('### Table M8 — authored platforms landed on by at least one run (union over policies and seeds)');
  P();
  P('| viewport | landed on | never landed on |');
  P('|---|---|---|');
  for (const vp of VPS) {
    const r = doc.reachByPlay[vp]; if (!r) continue;
    P(`| ${vp} | ${r.landedOn} of ${r.authored} | ${r.unreached.length ? r.unreached.join(', ') : '—'} |`);
  }
  P();
}
console.log(out.join('\n'));

/* -------- condensed: the compact tables quoted in the proposal ---------- */
function condensed() {
  const VSHORT = { 'desktop-16x10': 'desktop', 'phone-landscape': 'phone FAR', 'phone-landscape-6pct': 'phone 6 %', 'phone-portrait': 'portrait' };
  const sideCell = (f) => f.cleared
    ? `${m(f.faceSeconds)} (${m(f.movingSeconds)} / ${m(f.pivotWaitSeconds)} / ${m(f.gateHeldSeconds)})`
    : `— (0/${f.reached})`;
  P('**Table M1 — outcomes.** Cells: `median [min–max]` over the group\'s runs.');
  P();
  P('| group | viewport | n | outcomes | sides cleared | run s | lives lost | lethal events |');
  P('|---|---|---:|---|---|---|---|---|');
  for (const vp of VPS) for (const g of GROUPS) {
    const r = row(g, vp); if (!r) continue;
    P(`| ${g} | ${VSHORT[vp]} | ${r.n} | ${Object.entries(r.outcomes).map(([k, v]) => `${k} ${v}`).join(', ')} | ${mr(r.facesCleared, 0)} | ${mr(r.runSeconds)} | ${mr(r.livesLost, 0)} | ${mr(r.lethalEvents, 0)} |`);
  }
  P();
  P('**Table M2 — seconds per side.** Cell: `total (moving / waiting at the closed joint / gate held)`, medians over sides cleared. "Waiting at the joint" is part of "moving": the scroll is still running while RIG stands at the closed joint.');
  P();
  P('| group | viewport | side 1 | side 2 | side 3 | side 4 | side 5 | side 6 |');
  P('|---|---|---|---|---|---|---|---|');
  for (const vp of ['desktop-16x10', 'phone-landscape-6pct', 'phone-portrait']) for (const g of GROUPS) {
    const r = row(g, vp); if (!r || g === 'idle') continue;
    P(`| ${g} | ${VSHORT[vp]} | ${r.perFace.map(sideCell).join(' | ')} |`);
  }
  P();
  P('**Table M3 — seconds the scroll is held in `gate` per side** (every side reached, cleared or not; `median [min–max]`).');
  P();
  P('| group | viewport | gate 1 | gate 2 | gate 3 | gate 4 | gate 5 | gate 6 |');
  P('|---|---|---|---|---|---|---|---|');
  for (const vp of VPS) for (const g of GROUPS) {
    const r = row(g, vp); if (!r || g === 'idle') continue;
    if (!g.startsWith('oracle') && vp !== 'desktop-16x10' && vp !== 'phone-landscape-6pct') continue;
    P(`| ${g} | ${VSHORT[vp]} | ${r.perFace.map((f) => mr(f.gateStateSecondsAll)).join(' | ')} |`);
  }
  P();
  P('**Table M4 — vertical metres, desktop** (medians over sides; HUD metres). `peak` = highest local y above the side\'s lowest deck; `net` = HUD ALT gained from this side\'s entry to the next side\'s entry; `up/s` = all upward travel per second.');
  P();
  P('| group | peak above deck, sides 1–6 | net ALT m per side | net ALT m/s | climb-up m/s |');
  P('|---|---|---|---|---|');
  for (const g of GROUPS) {
    const r = row(g, 'desktop-16x10'); if (!r || g === 'idle') continue;
    const list = (k, d = 1) => r.perFace.map((f) => m(f[k], d)).join(' · ');
    P(`| ${g} | ${list('peakAboveDeck')} | ${list('netAltGain')} | ${list('netAltPerSecond', 2)} | ${list('climbUpPerSecond', 2)} |`);
  }
  P();
  P('**Table M5 — moving forward vs waiting** (whole run, share of frames; `median [min–max]`).');
  P();
  P('| group | viewport | forward ≥ 1 t/s | scroll held | pinned at right clamp | idle (A.5) |');
  P('|---|---|---|---|---|---|');
  for (const vp of ['desktop-16x10', 'phone-landscape-6pct']) for (const g of GROUPS) {
    const r = row(g, vp); if (!r) continue;
    P(`| ${g} | ${VSHORT[vp]} | ${pct(r.shareForward)} | ${pct(r.shareScrollHeld)} | ${pct(r.sharePinnedRight)} | ${pct(r.shareIdle)} |`);
  }
  P();
  P('**Table M6 — deaths per side.** Cell: `lethal events / lives spent` (medians; a lethal event is a HULL FALLBACK absorbed or a life spent).');
  P();
  P('| group | viewport | side 1 | side 2 | side 3 | side 4 | side 5 | side 6 |');
  P('|---|---|---|---|---|---|---|---|');
  for (const vp of ['desktop-16x10', 'phone-landscape-6pct']) for (const g of GROUPS) {
    const r = row(g, vp); if (!r || g === 'idle') continue;
    P(`| ${g} | ${VSHORT[vp]} | ${r.perFace.map((f) => f.reached ? `${m(f.lethalEvents, 0)} / ${m(f.livesLost, 0)}` : '—').join(' | ')} |`);
  }
  P();
  P('**Table M7 — how far ahead RIG can see.** Tiles of ROUTE ahead of RIG\'s front (to the right screen edge, clipped at the active corner\'s bend — beyond it the next side is round the limb), counted only on frames where the pursuing edge is moving (the race, not a held gate). `p10 / median / p90`; in brackets the share of those frames with < 3 tiles of route visible.');
  P();
  P('| group | desktop | phone FAR | phone 6 % | portrait |');
  P('|---|---|---|---|---|');
  for (const g of GROUPS) {
    const cell = (vp) => { const r = row(g, vp); const q = r && r.routeAheadMovingTiles; return q ? `${q.p10} / ${q.median} / ${q.p90} (${Math.round(q.shareUnder3 * 100)}%)` : '—'; };
    P(`| ${g} | ${cell('desktop-16x10')} | ${cell('phone-landscape')} | ${cell('phone-landscape-6pct')} | ${cell('phone-portrait')} |`);
  }
  P();
  P('**Table M7b — daylight behind RIG.** Tiles from RIG\'s back to the damage plane (the left edge) on every PLAYING frame: the margin entry 11 banks, and the crush margin. `p10 / median / p90`; in brackets the share of frames with < 3 tiles.');
  P();
  P('| group | desktop | phone FAR | phone 6 % | portrait |');
  P('|---|---|---|---|---|');
  for (const g of GROUPS) {
    const cell = (vp) => { const r = row(g, vp); const q = r && r.marginTiles; return q ? `${q.p10} / ${q.median} / ${q.p90} (${Math.round(q.shareUnder3 * 100)}%)` : '—'; };
    P(`| ${g} | ${cell('desktop-16x10')} | ${cell('phone-landscape')} | ${cell('phone-landscape-6pct')} | ${cell('phone-portrait')} |`);
  }
  P();
  P('**Table M8 — reachability by play and terrain stalls.** Authored platforms that at least one run of the matrix stood on, per viewport (union over every policy and seed), and seconds per side a policy pressed forward against terrain while not at the right clamp.');
  P();
  P('| viewport | authored platforms landed on | never landed on |');
  P('|---|---|---|');
  for (const vp of VPS) {
    const r = doc.reachByPlay && doc.reachByPlay[vp]; if (!r) continue;
    P(`| ${VSHORT[vp]} | ${r.landedOn} of ${r.authored} | ${r.unreached.length ? r.unreached.join(', ') : '—'} |`);
  }
  P();
  P('| group | viewport | terrain-stall s, sides 1–6 (median) |');
  P('|---|---|---|');
  for (const vp of ['desktop-16x10', 'phone-landscape-6pct']) for (const g of ['oracle@0', 'rush', 'climber', 'fighter', 'carried']) {
    const r = row(g, vp); if (!r) continue;
    P(`| ${g} | ${VSHORT[vp]} | ${r.perFace.map((f) => m(f.terrainStallSeconds, 1)).join(' · ')} |`);
  }
  P();
}
