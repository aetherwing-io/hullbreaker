#!/usr/bin/env node

/* Deterministically extract the small browser spec from the accepted asset
   manifest. Run after every atlas repack. The generated module carries both
   the manifest file hash and a semantic component-contract hash so a changed
   crop, pivot, socket, cell or source layer cannot silently keep stale runtime
   geometry. */

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const manifestFile = join(root,
  'assets/generated/enemy-ecology/level1-enemy-ecology-atlas-v1.manifest.json');
const outputFile = join(root, 'src/render/enemy-ecology-spec.js');
const source = readFileSync(manifestFile);
const manifest = JSON.parse(source);
const CELL = manifest.textureBudget.cellPx;

function sha256(value) {
  return createHash('sha256').update(value).digest('hex');
}

function componentContract(component) {
  return {
    id: component.id,
    contentSha256: component.contentSha256,
    cell: component.atlas.cell,
    visiblePx: component.atlas.visiblePx,
    pivot: component.pivot.cellPx,
    root: component.sockets.root.cellPx,
    attack: component.sockets.attack.cellPx,
  };
}

if (manifest.variants.length !== 12 || manifest.components.length !== 192 ||
    CELL !== 160 || manifest.textureBudget.width !== 3840 ||
    manifest.textureBudget.height !== 1280)
  throw new Error('enemy ecology manifest shape changed; refuse to emit runtime spec');

const byId = new Map(manifest.components.map((row) => [row.id, row]));
const packed = [];
const defs = [];
for (const variant of manifest.variants) {
  const bodyBounds = [];
  const actionBounds = [];
  const firstBody = byId.get(`${variant.id}-b0`);
  const firstAction = byId.get(`${variant.id}-a0`);
  let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
  for (let row = 0; row < 8; row++) {
    const body = byId.get(`${variant.id}-b${row}`);
    const action = byId.get(`${variant.id}-a${row}`);
    if (!body || !action) throw new Error(`${variant.id}: missing row ${row}`);
    const rootPx = body.sockets.root.cellPx;
    const bodyPivot = body.pivot.cellPx;
    const actionPivot = action.pivot.cellPx;
    const actionAttack = action.sockets.attack.cellPx;
    packed.push(...rootPx, ...bodyPivot, ...actionPivot, ...actionAttack);

    const bodyCol = body.atlas.cell[0], bodyRow = body.atlas.cell[1];
    const actionCol = action.atlas.cell[0], actionRow = action.atlas.cell[1];
    const [bx, by, bw, bh] = body.atlas.visiblePx;
    const [ax, ay, aw, ah] = action.atlas.visiblePx;
    const bx0 = bx - bodyCol * CELL, by0 = by - bodyRow * CELL;
    const ax0 = ax - actionCol * CELL, ay0 = ay - actionRow * CELL;
    bodyBounds.push([
      bx0 - rootPx[0], rootPx[1] - (by0 + bh),
      bx0 + bw - rootPx[0], rootPx[1] - by0,
    ]);
    actionBounds.push([
      ax0 - actionPivot[0], actionPivot[1] - (ay0 + ah),
      ax0 + aw - actionPivot[0], actionPivot[1] - ay0,
    ]);
  }
  for (let b = 0; b < 8; b++) for (let a = 0; a < 8; a++) {
    const body = byId.get(`${variant.id}-b${b}`);
    const rootPx = body.sockets.root.cellPx;
    const pivot = body.pivot.cellPx;
    const dx = pivot[0] - rootPx[0];
    const dy = rootPx[1] - pivot[1];
    const bb = bodyBounds[b], ab = actionBounds[a];
    minX = Math.min(minX, bb[0], dx + ab[0]);
    minY = Math.min(minY, bb[1], dy + ab[1]);
    maxX = Math.max(maxX, bb[2], dx + ab[2]);
    maxY = Math.max(maxY, bb[3], dy + ab[3]);
  }
  defs.push([
    variant.id, variant.family, variant.kind,
    firstBody.atlas.cell[0], firstAction.atlas.cell[0],
    [minX, minY, maxX, maxY].map((value) => Number(value.toFixed(6))),
  ]);
}

const quantized = Int16Array.from(packed.map((value) => {
  const q = Math.round(value * 16);
  if (q < -32768 || q > 32767) throw new Error(`coordinate out of Int16 range: ${value}`);
  return q;
}));
const payload = Buffer.from(quantized.buffer).toString('base64');
const chunks = payload.match(/.{1,100}/g);
const componentSha = sha256(JSON.stringify(manifest.components.map(componentContract)));
const manifestSha = sha256(source);
const defsSource = JSON.stringify(defs, null, 2).replace(/^/gm, '  ');
const packedSource = chunks.map((chunk) => `'${chunk}'`).join(' +\n  ');

const output = `/* AUTO-GENERATED by tools/assets/build-enemy-ecology-runtime-spec.mjs.
   Do not edit: repack the atlas, then regenerate this file. */

export const ENEMY_ECOLOGY_MANIFEST_SHA256 = '${manifestSha}';
export const ENEMY_ECOLOGY_COMPONENT_SHA256 = '${componentSha}';

export const ENEMY_ECOLOGY_ATLAS = Object.freeze({
  file: '../../assets/generated/enemy-ecology/level1-enemy-ecology-atlas-v1.webp',
  sourceFile: '../../assets/generated/enemy-ecology/level1-enemy-ecology-atlas-v1.png',
  canvas: Object.freeze([3840, 1280]),
  grid: Object.freeze([24, 8]),
  cellPx: 160,
  componentCount: 192,
  visualStateCount: 768,
  estimatedGpuBytes: 26214400,
});

const DEFS = Object.freeze(${defsSource.trimStart()});
const PACKED = ${packedSource};
const VALUES_PER_ROW = 8;

function decodeRows() {
  const binary = atob(PACKED);
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i);
  const view = new DataView(bytes.buffer);
  const variants = [];
  for (let variant = 0; variant < DEFS.length; variant++) {
    const rows = [];
    for (let row = 0; row < 8; row++) {
      const base = (variant * 8 + row) * VALUES_PER_ROW * 2;
      const read = (index) => view.getInt16(base + index * 2, true) / 16;
      rows.push(Object.freeze({
        bodyRoot: Object.freeze([read(0), read(1)]),
        bodyPivot: Object.freeze([read(2), read(3)]),
        actionPivot: Object.freeze([read(4), read(5)]),
        actionAttack: Object.freeze([read(6), read(7)]),
      }));
    }
    variants.push(Object.freeze(rows));
  }
  return variants;
}

const ROWS = decodeRows();
const variantById = new Map();
export const ENEMY_ECOLOGY_VARIANTS = Object.freeze(DEFS.map((def, index) => {
  const [id, family, kind, bodyColumn, actionColumn, bounds] = def;
  const variant = Object.freeze({
    id, family, kind, bodyColumn, actionColumn,
    grounded: family !== 'aerial',
    bounds: Object.freeze(bounds),
    rows: ROWS[index],
  });
  variantById.set(id, variant);
  return variant;
}));

export function enemyEcologyVariant(id, kind = '') {
  const variant = variantById.get(id);
  return variant && (!kind || variant.kind === kind) ? variant : null;
}
`;

writeFileSync(outputFile, output);
console.log(JSON.stringify({
  output: outputFile.slice(root.length + 1),
  manifestSha256: manifestSha,
  componentSha256: componentSha,
  variants: defs.length,
  components: manifest.components.length,
  packedBytes: quantized.byteLength,
}, null, 2));
